// swift-tools-version: 5.9
//
// hoi for iOS: the Rust core (HoiCoreFFI.xcframework + generated Swift bindings), a small
// SwiftUI-friendly wrapper (HoiCore) and the design tokens (HoiTheme).
//
// Run ../../scripts/build-ios.sh first: it builds Frameworks/HoiCoreFFI.xcframework and writes
// the generated bindings into Sources/HoiCoreFFI/ (both gitignored).

import PackageDescription

let package = Package(
    name: "HoiCore",
    platforms: [.iOS(.v16), .macOS(.v13)],
    products: [
        .library(name: "HoiCore", targets: ["HoiCore"]),
        .library(name: "HoiTheme", targets: ["HoiTheme"]),
    ],
    targets: [
        // The Rust static libraries and the C headers of both UniFFI crates, as one Clang
        // module named HoiCoreFFI (Headers/HoiCoreFFI/module.modulemap).
        .binaryTarget(name: "HoiCoreFFI", path: "Frameworks/HoiCoreFFI.xcframework"),
        // Generated bindings (Sources/HoiCoreFFI/*.swift) and the hand-written wrapper
        // (Sources/HoiCore/) compile into one Swift module: `import HoiCore` gives you both.
        .target(
            name: "HoiCore",
            dependencies: ["HoiCoreFFI"],
            path: "Sources",
            exclude: ["HoiTheme"],
            sources: ["HoiCore", "HoiCoreFFI"]
        ),
        // Colours, spacing, radii and motion from design/tokens (HoiTokens.swift is generated by
        // `pnpm tokens`), plus font helpers.
        .target(name: "HoiTheme", path: "Sources/HoiTheme"),
    ]
)
